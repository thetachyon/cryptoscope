#!/usr/bin/env python3
"""Vendor the shared code into each *Scope app.

Canonical sources (edit these, never the copies):
  common/    — shared Python package (chain registry, clients, pricing,
               formatting, ABI codec, explorer core, wallet, factories)
  frontend/  — shared SPA (index.html, app.js, styles.css, labels.json)

Each app (<app>/config.py is the single source of truth for that app's
metadata) gets:
  <app>/common/       — fresh copy of common/ (generated, never hand-edit)
  <app>/static/       — fresh copy of frontend/ (generated, never hand-edit)
  <app>/static/config.js — GENERATED from <app>/config.py (never hand-edit)

Frontend overlay: an app may ship its own <app>/frontend/ directory
(solscope does — the EVM SPA does not fit Solana). Its files, limited
to the FRONTEND_FILES names, are copied over the canonical ones in
<app>/static/ after the canonical copy, and `check` compares them
against the overlay source instead of the canonical files. Edit the
overlay source, never the generated static/ copies.

Usage:
  python3 scripts/sync-common.py sync    # copy canonical -> apps (default)
  python3 scripts/sync-common.py check   # verify apps match canonical

Vercel: each app's vercel.json runs this script as its buildCommand, so a
deploy always bundles the latest shared code even if a committed copy is
stale. The committed copies exist so local runs work without the script
and so a buildCommand failure can never break a deploy — `check` is the
guard that the copies match.
"""
import hashlib
import importlib.util
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMON_SRC = ROOT / "common"
FRONTEND_SRC = ROOT / "frontend"
FRONTEND_FILES = ["index.html", "app.js", "styles.css", "labels.json"]


def find_apps():
    """App dirs: subdirectories of the repo root containing config.py."""
    apps = []
    for d in sorted(ROOT.iterdir()):
        if d.is_dir() and (d / "config.py").exists():
            apps.append(d)
    return apps


def load_config(app_dir: Path):
    spec = importlib.util.spec_from_file_location(f"{app_dir.name}_config", app_dir / "config.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render_config_js(cfg, app_dir: Path) -> str:
    payload = {
        "scope": cfg.SCOPE,
        "title": cfg.TITLE,
        "brandLetter": getattr(cfg, "BRAND_LETTER", "E"),
        "chain": getattr(cfg, "CHAIN", None),
        "apiPrefix": f"/api/{cfg.SCOPE}",
        "walletOnly": bool(getattr(cfg, "WALLET_ONLY", False)),
        "walletUrl": getattr(cfg, "WALLET_URL", ""),
        "netpill": getattr(cfg, "NETPILL", None),
        "siblings": getattr(cfg, "SIBLINGS", []),
    }
    return (
        "// GENERATED by scripts/sync-common.py from "
        + app_dir.name
        + "/config.py — do not hand-edit.\n"
        + "// Regenerate: python3 scripts/sync-common.py sync\n"
        + "window.SCOPE_CONFIG = "
        + json.dumps(payload, indent=2)
        + ";\n"
    )


def _copy_tree(src: Path, dst: Path):
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def _sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _tree_files(d: Path):
    return sorted(
        p.relative_to(d)
        for p in d.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    )


def sync_app(app_dir: Path):
    cfg = load_config(app_dir)
    _copy_tree(COMMON_SRC, app_dir / "common")
    static = app_dir / "static"
    static.mkdir(exist_ok=True)
    for f in FRONTEND_FILES:
        shutil.copy2(FRONTEND_SRC / f, static / f)
    # Per-app frontend overlay (solscope): same filenames only.
    overlay = app_dir / "frontend"
    if overlay.is_dir():
        for f in FRONTEND_FILES:
            src = overlay / f
            if src.exists():
                shutil.copy2(src, static / f)
    (static / "config.js").write_text(render_config_js(cfg, app_dir))
    print(f"synced {app_dir.name}: common/ + static/ + config.js")


def check_app(app_dir: Path):
    """Return a list of mismatch descriptions (empty = in sync)."""
    problems = []
    cfg = load_config(app_dir)
    # common/
    want = {f: _sha256(COMMON_SRC / f) for f in _tree_files(COMMON_SRC)}
    have_dir = app_dir / "common"
    have = {f: _sha256(have_dir / f) for f in _tree_files(have_dir)} if have_dir.exists() else {}
    if want != have:
        for f in sorted(set(want) | set(have)):
            if want.get(f) != have.get(f):
                problems.append(f"{app_dir.name}/common/{f}: differs from canonical")
    # static/ (frontend files only; config.js checked separately).
    # An app's frontend/ overlay replaces the canonical source for the
    # files it provides (solscope).
    static = app_dir / "static"
    overlay = app_dir / "frontend"
    for f in FRONTEND_FILES:
        src = (overlay / f) if (overlay.is_dir() and (overlay / f).exists()) else (FRONTEND_SRC / f)
        dst = static / f
        if not dst.exists() or _sha256(src) != _sha256(dst):
            problems.append(f"{app_dir.name}/static/{f}: differs from {'overlay' if src.parent == overlay else 'canonical'}")
    want_cfg = render_config_js(cfg, app_dir)
    got_cfg = (static / "config.js").read_text() if (static / "config.js").exists() else ""
    if want_cfg != got_cfg:
        problems.append(f"{app_dir.name}/static/config.js: differs from generated")
    return problems


def main(argv):
    mode = argv[1] if len(argv) > 1 else "sync"
    apps = find_apps()
    if not apps:
        print("no apps found (expected subdirectories with config.py)")
        return 1
    if mode == "sync":
        for app_dir in apps:
            sync_app(app_dir)
        return 0
    if mode == "check":
        problems = []
        for app_dir in apps:
            problems.extend(check_app(app_dir))
        if problems:
            print("OUT OF SYNC:")
            for p in problems:
                print("  -", p)
            return 1
        print(f"in sync: {len(apps)} apps match canonical common/ + frontend/")
        return 0
    print("usage: sync-common.py [sync|check]")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
