/* ---------------- search ---------------- */
function classify(q) {
  q = String(q || "").trim();
  if (/^0x[0-9a-fA-F]{64}$/.test(q)) return { kind: "tx", v: q };
  if (/^0x[0-9a-fA-F]{40}$/.test(q)) return { kind: "address", v: q };
  if (/^\d+$/.test(q)) return { kind: "block", v: q };
  if (q.length >= 2) return { kind: "query", v: q };
  return null;
}
async function doSearch(q) {
  const c = classify(q);
  if (!c) return;
  if (WALLET_ONLY) {
    // WalletScope searches addresses and ENS names only.
    if (c.kind === "address") { location.hash = "#/wallet/" + c.v; return; }
    if (c.kind === "query") {
      try {
        const d = await get("/search?q=" + encodeURIComponent(c.v));
        const hit = (d.items || []).find((it) => it.type === "address");
        if (hit) { location.hash = "#/wallet/" + hit.hash; return; }
        banner("No address found for “" + c.v + "”");
      } catch (e) { banner(e.message); }
      return;
    }
    banner("WalletScope searches addresses and ENS names only.");
    return;
  }
  if (c.kind === "tx") location.hash = "#/tx/" + c.v;
  else if (c.kind === "address") location.hash = "#/address/" + c.v;
  else if (c.kind === "block") location.hash = "#/block/" + c.v;
  else {
    try {
      const d = await get("/search?q=" + encodeURIComponent(c.v));
      if (d.items && d.items.length) {
        const it = d.items[0];
        if (it.type === "address") location.hash = "#/address/" + it.hash;
        else if (it.type === "token") location.hash = "#/token/" + it.hash;
        else if (it.type === "transaction") location.hash = "#/tx/" + it.hash;
        else if (it.type === "block") location.hash = "#/block/" + (it.block_number || it.hash);
        else banner("No results for “" + c.v + "”");
      } else banner("No results for “" + c.v + "”");
    } catch (e) { banner(e.message); }
  }
}
function wireSearch(form, input, suggestBox) {
  if (!form || !input || !suggestBox) return;
  let timer = null;
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    suggestBox.classList.add("hidden");
    doSearch(input.value);
  });
  input.addEventListener("input", () => {
    clearTimeout(timer);
    const q = input.value.trim();
    if (q.length < 3) { suggestBox.classList.add("hidden"); return; }
    timer = setTimeout(async () => {
      try {
        const d = await get("/search?q=" + encodeURIComponent(q));
        const items = WALLET_ONLY ? (d.items || []).filter((it) => it.type === "address") : (d.items || []);
        if (!items.length) { suggestBox.classList.add("hidden"); return; }
        suggestBox.innerHTML = items.map((it) => {
          const route = it.type === "address" ? (WALLET_ONLY ? "#/wallet/" + it.hash : "#/address/" + it.hash)
            : it.type === "token" ? "#/token/" + it.hash
            : it.type === "transaction" ? "#/tx/" + it.hash
            : it.type === "block" ? "#/block/" + (it.block_number || it.hash) : null;
          if (!route) return "";
          const main = `<a href="${route}"><span class="stype ${it.type}">${esc(it.type)}</span><span class="mono">${esc(it.name)}</span></a>`;
          // Address rows get a second link straight to the wallet dashboard.
          return it.type === "address" && !WALLET_ONLY
            ? `<div class="suggest-row">${main}<a class="wallet-link" href="${walletHref(it.hash)}" title="Open wallet dashboard">💼 Wallet</a></div>`
            : main;
        }).join("");
        suggestBox.classList.remove("hidden");
      } catch (e) { /* silent */ }
    }, 300);
  });
  document.addEventListener("click", (e) => {
    if (!form.contains(e.target)) suggestBox.classList.add("hidden");
  });
}

